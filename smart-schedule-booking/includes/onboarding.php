function fp_help_launch_status() {
    global $wpdb;
    $t = function_exists('fp_sched_tables') ? fp_sched_tables() : [];
    $uid = get_current_user_id();
    $events = !empty($t['events']) ? (int)$wpdb->get_var($wpdb->prepare("SELECT COUNT(*) FROM {$t['events']} WHERE user_id=%d AND active=1",$uid)) : 0;
    $availability = (!empty($t['availability']) && $events) ? (int)$wpdb->get_var("SELECT COUNT(*) FROM {$t['availability']}") : 0;
    $workflows = !empty($t['workflows']) ? (int)$wpdb->get_var($wpdb->prepare("SELECT COUNT(*) FROM {$t['workflows']} WHERE user_id=%d",$uid)) : 0;
    $license = function_exists('ssb_license_status') ? ssb_license_status() : ['active'=>false];
    $integrated = (function_exists('ssb_google_is_connected') && ssb_google_is_connected()) || !empty(get_option('ssb_stripe_secret_key'));
    if(function_exists('fp_adv_integration')) foreach(['zoom','teams','hubspot','salesforce'] as $p) if(fp_adv_integration($uid,$p)){$integrated=true;break;}
    $brand = get_option('fp_sched_branding',[]);
    return [
        ['done'=>!empty($license['active']),'label'=>'License active','link'=>admin_url('admin.php?page=ssb-license')],
        ['done'=>$integrated,'label'=>'At least one provider connected','link'=>admin_url('admin.php?page=fp-integrations')],
        ['done'=>$events>0,'label'=>'At least one active event type','link'=>admin_url('admin.php?page=fp-scheduling')],
        ['done'=>$availability>0,'label'=>'Availability configured','link'=>admin_url('admin.php?page=fp-availability')],
        ['done'=>$workflows>0,'label'=>'Confirmation/reminder workflow reviewed','link'=>admin_url('admin.php?page=fp-workflows')],
        ['done'=>!empty($brand['logo'])||!empty($brand['accent']),'label'=>'Public scheduler branding reviewed','link'=>admin_url('admin.php?page=fp-branding')],
    ];
}

