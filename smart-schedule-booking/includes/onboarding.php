function fp_help_current_page() {
    if ( ! is_admin() || empty($_GET['page']) ) return '';
    return sanitize_key(wp_unslash($_GET['page']));
}

add_action('admin_notices', 'fp_help_context_notice', 2);
function fp_help_context_notice() {
    if ( ! current_user_can('manage_options') ) return;
    $page = fp_help_current_page();
    if ( ! $page || $page === 'fp-help' ) return;
    $catalog = fp_help_pages();
    if ( empty($catalog[$page]) ) return;
    $g = $catalog[$page];
    echo '<div class="fp-context-help">';
    echo '<details'.($page==='fp-integrations'?' open':'').'>';
    echo '<summary><span class="dashicons dashicons-lightbulb"></span><strong>'.esc_html($g['title']).'</strong><span class="fp-help-summary-copy">'.esc_html($g['summary']).'</span><span class="fp-help-open">Guide</span></summary>';
    echo '<div class="fp-help-body"><div class="fp-help-columns"><div><h3>Quick start</h3><ol>';
    foreach($g['steps'] as $s) echo '<li>'.esc_html($s).'</li>';
    echo '</ol></div><div class="fp-example-box"><span>EXAMPLE</span><p>'.esc_html($g['example']).'</p></div></div>';
    if ( ! empty($g['integrations']) ) fp_help_render_integrations();
    echo '<p class="fp-help-more"><a href="'.esc_url(admin_url('admin.php?page=fp-help')).'">Open the complete FormPilot Launch Guide →</a></p>';
    echo '</div></details></div>';
}

